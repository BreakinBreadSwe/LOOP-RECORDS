"""Write supabase/seed.sql from data/catalog.json: labels, people, releases, artists, tracks and credits.
Ids are stable (Discogs ids, plus uuid5 for tracks and credits) so the seed can be re-run safely."""
import json, pathlib, uuid
ROOT = pathlib.Path(__file__).resolve().parent.parent
cat = json.loads((ROOT / "data/catalog.json").read_text())
art = json.loads((ROOT / "data/artwork.json").read_text())
NS = uuid.UUID("6f0c2a52-1b1e-4c55-9a4e-4c4f4f505245")
q = lambda v: "null" if v is None or v == "" else "'" + str(v).replace("'", "''") + "'"
arr = lambda xs: "'{" + ",".join('"' + str(x).replace('\\', '\\\\').replace('"', '\\"').replace("'", "''") + '"' for x in xs) + "}'"
out = ["-- Generated by scripts/make_seed.py from data/catalog.json. Safe to re-run.", "begin;"]
out.append("insert into public.labels (id,name,discogs_id,city,country,founded) values "
           "('loop','Loop Records',179847,'Stockholm','Sweden',1993),('plumphouse','Plumphouse Records',310,'Stockholm','Sweden',1995) on conflict (id) do nothing;")
for p in cat["people"]:
    out.append(f"insert into public.people (key,discogs_id,name,aliases) values ({q(p['key'])},{p['discogsId'] or 'null'},{q(p['name'])},{arr(p['aliases'])}) on conflict (key) do update set name=excluded.name, aliases=excluded.aliases;")
for r in cat["releases"]:
    label = {"loop": "'loop'", "plump": "'plumphouse'"}.get(r["group"], "null")
    imgs = art.get(str(r["id"])) or []
    out.append("insert into public.releases (id,label_id,grp,catno,title,year,released,country,format,genres,styles,artwork_url,discogs_url) values "
               f"({r['id']},{label},{q(r['group'])},{q(r['catno'])},{q(r['title'])},{r['year'] or 'null'},{q(r['released'])},{q(r['country'])},{q(r['format'])},{arr(r['genres'])},{arr(r['styles'])},{q(imgs[0] if imgs else None)},{q(r['discogs'])}) "
               "on conflict (id) do update set title=excluded.title, catno=excluded.catno, artwork_url=coalesce(excluded.artwork_url, public.releases.artwork_url);")
    for i, a in enumerate(r["artists"]):
        out.append(f"insert into public.release_artists (release_id,person_key,position) values ({r['id']},{q(a['key'])},{i}) on conflict do nothing;")
    for c in r["credits"]:
        cid = uuid.uuid5(NS, f"c:{r['id']}::{c['key']}:{c['role']}")
        out.append(f"insert into public.credits (id,release_id,track_id,person_key,role) values ('{cid}',{r['id']},null,{q(c['key'])},{q(c['role'])}) on conflict (id) do nothing;")
    for t in r["tracks"]:
        tid = uuid.uuid5(NS, f"t:{r['id']}:{t['pos']}:{t['title']}")
        out.append(f"insert into public.tracks (id,release_id,position,title,duration) values ('{tid}',{r['id']},{q(t['pos'])},{q(t['title'])},{q(t['dur'])}) on conflict (id) do nothing;")
        for c in t["credits"] + [{"key": a["key"], "role": "Track artist"} for a in t["artists"]]:
            cid = uuid.uuid5(NS, f"c:{r['id']}:{t['pos']}:{c['key']}:{c['role']}")
            out.append(f"insert into public.credits (id,release_id,track_id,person_key,role) values ('{cid}',{r['id']},'{tid}',{q(c['key'])},{q(c['role'])}) on conflict (id) do nothing;")
out.append("commit;")
(ROOT / "supabase/seed.sql").write_text("\n".join(out) + "\n")
print(len(out), "statements")
